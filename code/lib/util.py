"""Small helpers shared by the scripts: LaTeX table writer, macro registry, stars."""
import json
import numpy as np
from config import TAB

_MACRO_JSON = TAB / "macros.json"
_MACRO_TEX = TAB / "macros.tex"


def set_macros(d):
    """Merge {name: value} into the macro registry and rewrite macros.tex.

    Macro names must contain letters only (LaTeX restriction)."""
    cur = json.loads(_MACRO_JSON.read_text()) if _MACRO_JSON.exists() else {}
    cur.update({k: str(v) for k, v in d.items()})
    _MACRO_JSON.write_text(json.dumps(cur, indent=1, sort_keys=True))
    lines = ["% Generated by the scripts in code/ (numbers quoted in the text); regenerate with code/run_all.py."]
    for k, v in sorted(cur.items()):
        assert k.isalpha(), f"macro name must be letters only: {k}"
        lines.append("\\newcommand{\\%s}{%s}" % (k, v))
    _MACRO_TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.10 else ""


def fmt(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    return f"{x:.{d}f}"


def coef_cell(b, se, p, d=3):
    return f"{b:.{d}f}{stars(p)}", f"({se:.{d}f})"


def tabular(rows, colspec, header=None, midrules=(), note=None, resize=False):
    """Return a booktabs tabular.  rows: list of list[str].  Note goes under the table."""
    out = []
    if resize:
        out.append("\\resizebox{\\tablewidth}{!}{%")
    out.append("\\begin{tabular}{%s}\\toprule" % colspec)
    if header:
        for h in header:
            out.append(" & ".join(h) + " \\\\")
        out.append("\\midrule")
    for i, r in enumerate(rows):
        out.append(" & ".join(r) + " \\\\")
        if i in midrules:
            out.append("\\midrule")
    out.append("\\bottomrule\\end{tabular}")
    if resize:
        out.append("}")
    if note:
        out.append("\\\\[3pt]\\begin{minipage}{\\tablewidth}\\footnotesize " + note + "\\end{minipage}")
    return "\n".join(out) + "\n"
